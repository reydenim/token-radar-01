// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other rankable pre-token protocol below it: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The market multiple is the model's
// core: for each category, the median market-cap-per-TVL of the live-token protocols in that same
// category — what the market actually pays per dollar of TVL for that kind of protocol. A category
// with fewer than two live comps falls back to the global median across all live protocols. The
// multiple is clamped to a sane band so one odd comp cannot set it. No protocol name is ever
// special-cased: the same function scores every row.
//
//   categoryMultiple = clamp(median(mcap_usd / tvl_usd over live comps in the category), 0.05, 1.0)
//   base       = tvl_usd x categoryMultiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.05 x min(chains - 1, 3)   (more chains, more surface for a launch)
//   implied    = max(1, round(base x growthMult x maturity x breadth))

